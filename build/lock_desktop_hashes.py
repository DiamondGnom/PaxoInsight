"""Generate reviewed Windows x64 wheel hashes for the exact desktop locks.

Run explicitly after reviewing a dependency update, with standard Python 3.14.
No package code is installed or executed. Source distributions are never accepted.
"""

from __future__ import annotations

import concurrent.futures
import json
import urllib.request
from pathlib import Path

try:
    from packaging.tags import sys_tags
    from packaging.utils import parse_wheel_filename
except ImportError:
    from pip._vendor.packaging.tags import sys_tags
    from pip._vendor.packaging.utils import parse_wheel_filename

ROOT = Path(__file__).resolve().parents[1]


def pins(path: Path) -> dict[str, str]:
    result = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line.startswith("-r "):
            result.update(pins(ROOT / line[3:]))
        elif line and not line.startswith("#"):
            name, version = line.split("==")
            result[name] = version
    return result


def lock(target: str) -> None:
    tags = set(sys_tags())
    versions = pins(ROOT / f"requirements-{target}.lock.txt")

    def fetch(item):
        name, version = item
        url = f"https://pypi.org/pypi/{name}/{version}/json"
        with urllib.request.urlopen(url, timeout=45) as response:
            release = json.load(response)
        hashes = sorted({entry["digests"]["sha256"] for entry in release["urls"]
                         if entry["packagetype"] == "bdist_wheel" and not entry.get("yanked")
                         and parse_wheel_filename(entry["filename"])[3] & tags})
        if not hashes:
            raise RuntimeError(f"No compatible wheel for {name}=={version}")
        continuation = " " + chr(92) + "\n    "
        return continuation.join([f"{name}=={version}",
                                  *(f"--hash=sha256:{digest}" for digest in hashes)])

    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        rows = list(pool.map(fetch, versions.items()))
    text = "# Standard CPython 3.14.8 Windows x64; generated by build/lock_desktop_hashes.py.\n"
    text += "# Exact reviewed versions from the corresponding .lock.txt; no source builds.\n"
    text += "--only-binary=:all:\n\n" + "\n".join(rows) + "\n"
    destination = ROOT / f"requirements-{target}.hashes.txt"
    destination.write_text(text, encoding="utf-8")
    print(f"Generated {destination.name}: {len(versions)} dependencies")


if __name__ == "__main__":
    lock("runtime")
    lock("build")
